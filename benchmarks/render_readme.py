#!/usr/bin/env python3
"""Generate the README results section from benchmark result JSONs.

Single source of truth: the JSONs under benchmarks/*/results/. The README
charts (publication-quality matplotlib PNGs under docs/media/charts/) and
tables are regenerated from them, so documentation can never drift from the
measured data.

Usage (from the repo root):
    python benchmarks/render_readme.py            # rewrite README.md + charts in place
    python benchmarks/render_readme.py --check    # exit 1 if README is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

BENCHMARKS_DIR = REPO_ROOT / "benchmarks"
CHARTS_DIR = REPO_ROOT / "docs" / "media" / "charts"
README = REPO_ROOT / "README.md"

RESULTS_BEGIN = "<!-- physgate:results:begin (auto-generated by benchmarks/render_readme.py — edit the JSONs, not this block) -->"
RESULTS_END = "<!-- physgate:results:end -->"

#: Pre-rebuild (milestone 2) feasibility — the artifact the rebuild eliminated.
PRE_REBUILD = {"mock": (2, 8), "claude": (1, 7), "pool_pct": 17}

CONDITION_NAMES = {
    "A0_no_validation": "A0 — No validation",
    "A1_critic_only": "A1 — + LLM critic",
    "A2_symbolic_gate": "A2 — + Symbolic gate",
    "A3_nav_aware_gate": "A3 — + Physics gate (nav + goal)",
}

LAYER_NAMES = {
    "critic": "LLM critic",
    "l1_l3": "+ L1/L3 deterministic checks",
    "symbolic_gate": "+ Symbolic L2 (full gate)",
    "physics_gate": "Isaac physics L2",
}


# ------------------------------------------------------------------ utilities


def _load(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def _pct(value: float) -> int:
    return int(round(value * 100))


def _chart_path_for_readme(chart_path: Path) -> str:
    """Chart path relative to the repo root (how the README references it)."""
    try:
        return str(chart_path.relative_to(REPO_ROOT))
    except ValueError:
        return str(chart_path)


# ------------------------------------------------------------------- sections


def _ablation_block(results_root: Path, charts_dir: Path) -> str:
    data = _load(results_root / "eval_v2" / "results" / "ablation.json")
    if data is None:
        return "_E1 ablation results not available — run `benchmarks/eval_v2/run_ablation.py`._\n"

    from physgate.viz.charts import ablation_chart

    chart = ablation_chart(data, charts_dir / "e1_ablation.png")

    config = data.get("config", {})
    rows = []
    for condition, outcome in data["conditions"].items():
        ci = outcome.get("success_ci_95", [None, None])
        ci_text = f"[{ci[0]:.2f}, {ci[1]:.2f}]" if ci[0] is not None else "—"
        rows.append(
            f"| {CONDITION_NAMES.get(condition, condition)} "
            f"| {outcome['success_rate']:.2f} {ci_text} "
            f"| {outcome['rejection_rate']:.2f} |"
        )

    return f"""### E1 — Pipeline ablation: what each validation layer is worth

The core experiment: the same contaminated plan pool (clean + defect-injected
plans) and the same generated task instances, run through four pipeline
configurations. Without validation, defective plans execute and fail; without
*physics/navigation-level* validation, impossible tasks are executed instead of
rejected.

![E1 pipeline ablation]({_chart_path_for_readme(chart)})

| Pipeline | Success rate (feasible tasks, 95% CI) | Rejection rate (infeasible tasks) |
|---|---|---|
{chr(10).join(rows)}

n = {config.get("n_feasible_instances", "?")} feasible + {config.get("n_infeasible_instances", "?")} infeasible
procedurally generated layouts (A*-certified labels); plan pool of
{config.get("plan_pool_size", "?")} plans. CIs are instance-level
(n = number of independent generated layouts, not plan × instance):
Wilson CI for binary per-instance outcomes (A2/A3), normal-approximation
CI for fractional per-instance rates (A0/A1). Methodology:
[`docs/design/EVALUATION_METHODOLOGY.md`](docs/design/EVALUATION_METHODOLOGY.md).
"""


def _classifier_block(results_root: Path, charts_dir: Path) -> str:
    data = _load(results_root / "eval_v2" / "results" / "gate_classifier.json")
    if data is None:
        return "_E2 classifier results not available — run `benchmarks/eval_v2/run_gate_classifier.py`._\n"

    from physgate.viz.charts import gate_classifier_chart

    chart = gate_classifier_chart(data, charts_dir / "e2_gate_classifier.png")

    rows = []
    for layer, layer_data in data["layers"].items():
        report = layer_data["report"]
        rows.append(
            f"| {LAYER_NAMES.get(layer, layer)} "
            f"| {report['precision']:.2f} | {report['recall']:.2f} | {report['f1']:.2f} "
            f"| {report['false_positive_rate']:.2f} "
            f"| {layer_data.get('wall_s', 0):.1f} s |"
        )

    return f"""### E2 — The gate as a classifier (defect-injection corpus)

Every validation layer scored as a binary classifier over a labeled corpus of
clean and systematically corrupted plans (defect taxonomy from the
plan-verification literature). This substantiates the layered-defense claim:
each layer catches strictly more defect classes, with zero false positives.

![E2 gate classifier]({_chart_path_for_readme(chart)})

| Validation layer | Precision | Recall | F1 | False-positive rate | Wall time |
|---|---|---|---|---|---|
{chr(10).join(rows)}

The physics gate matches the symbolic gate on plan-level defects (consistency
check) — its *unique* value is world-level infeasibility (E1's right panel) and
physical outcome verification, which no symbolic layer can provide.
"""


def _feasibility_block(results_root: Path, charts_dir: Path) -> str:
    data = _load(results_root / "rebuild" / "results" / "feasibility_after_rebuild.json")
    if data is None:
        return "_Feasibility results not available — run `benchmarks/rebuild/verify_feasibility.py`._\n"

    from physgate.viz.charts import feasibility_chart

    chart = feasibility_chart(data, charts_dir / "feasibility.png")

    # repeat statistics when available
    repeats_dir = results_root / "rebuild" / "results" / "repeats"
    repeat_files = sorted(repeats_dir.glob("feasibility_run_*.json")) if repeats_dir.exists() else []
    repeats_note = ""
    if repeat_files:
        totals: dict[str, list[tuple[int, int]]] = {}
        for path in repeat_files:
            run = _load(path)
            for m in run["measurements"]:
                totals.setdefault(m["planner"], []).append(
                    (m["physically_feasible"], m["critic_survivors"])
                )
        parts = []
        for planner, counts in totals.items():
            feasible = sum(c[0] for c in counts)
            total = sum(c[1] for c in counts)
            parts.append(
                f"{'Claude' if planner == 'claude' else 'mock'} {feasible}/{total} plans"
            )
        repeats_note = (
            f"\nRepeat statistics across {len(repeat_files)} independent runs "
            f"(fresh LLM generations each time): {'; '.join(parts)} — 100% ± 0%.\n"
        )

    rows = []
    for m in data["measurements"]:
        name = m["planner"]
        before_feasible, before_total = PRE_REBUILD.get(name, (0, 0))
        rows.append(
            f"| {'Real Claude' if name == 'claude' else 'Mock planner'} "
            f"| {before_feasible}/{before_total} ({_pct(before_feasible / before_total)}%) "
            f"| **{m['physically_feasible']}/{m['critic_survivors']} "
            f"({_pct(m['feasibility_of_survivors'])}%)** "
            f"| {m['gpu_wall_s']} s |"
        )

    return f"""### Feasibility — the 17% artifact is eliminated

Before the rebuild, "feasibility" measured whether the LLM happened to name a
hand-placed rescue waypoint (obstacle avoidance in the wrong layer). After the
rebuild (deterministic A* navigation), every well-formed decomposition is
physically feasible:

![Feasibility before/after]({_chart_path_for_readme(chart)})

| Planner | Pre-rebuild (artifact) | Post-rebuild | GPU wall |
|---|---|---|---|
{chr(10).join(rows)}
{repeats_note}"""


def _orchestration_block(results_root: Path, charts_dir: Path) -> str:
    data = _load(results_root / "orchestration" / "results" / "orchestration_eval.json")
    if data is None:
        return "_Orchestration results not available — run `benchmarks/orchestration/run_eval.py`._\n"

    from physgate.viz.charts import orchestrator_chart

    # repeat statistics when available
    repeats_dir = results_root / "orchestration" / "results" / "repeats"
    repeat_files = sorted(repeats_dir.glob("eval_run_*.json")) if repeats_dir.exists() else []
    repeats = [_load(p)["reports"] for p in repeat_files] if repeat_files else None

    chart = orchestrator_chart(
        data["reports"], charts_dir / "orchestrator.png", repeats=repeats
    )

    metric_names = [
        ("end_to_end_success_rate", "End-to-end success (feasible tasks)"),
        ("infeasible_recognition_rate", "Infeasible-task recognition"),
        ("recovery_rate", "Transient-failure recovery"),
        ("decomposition_validity_rate", "Decomposition validity"),
        ("invalid_plan_catch_rate", "Invalid-plan catch rate"),
        ("orchestrator_score", "**Orchestrator score**"),
    ]
    reports = {r["planner_name"]: r["metrics"] for r in data["reports"]}
    planners = list(reports)

    header = "| Metric | " + " | ".join(
        "Real Claude" if p == "llm" else "Mock planner" for p in planners
    )
    rows = [header + " |", "|---|" + "---|" * len(planners)]
    for key, label in metric_names:
        cells = " | ".join(f"{reports[p].get(key, 0.0):.2f}" for p in planners)
        rows.append(f"| {label} | {cells} |")

    stats_note = (
        f"\nError bars: mean ± sd over {len(repeat_files)} independent runs "
        "(fresh LLM plan generations each run).\n"
        if repeat_files
        else ""
    )

    return f"""### Orchestration regression suite (v1)

7 scenarios (ordering / preconditions / recovery / multi-step / infeasible) run
through the **real LangGraph orchestrator** with fault injection. Retained as a
regression test; the headline evidence is E1/E2 above.

![Orchestrator metrics]({_chart_path_for_readme(chart)})

{chr(10).join(rows)}
{stats_note}"""


def _gpu_block(results_root: Path, charts_dir: Path) -> str:
    data = _load(results_root / "phase0" / "results" / "benchmark_3_gpu_saturation.json")
    if data is None:
        return "_GPU scaling results not available — run `benchmarks/phase0/benchmark_3_gpu_saturation.py`._\n"

    from physgate.viz.charts import gpu_scaling_chart

    chart = gpu_scaling_chart(data, charts_dir / "gpu_scaling.png")

    results = data["results"]
    rows = [
        f"| {r['num_envs']} | {r['env_steps_per_s']:,.0f} | {r['scaling_efficiency']:.2f} |"
        for r in results
    ]
    knee = data.get("saturation_knee_envs")
    knee_note = (
        f"saturation knee at {knee} envs"
        if knee
        else "the saturation knee was **not reached** in the measured range — 1024 envs is the largest measured point, not a limit"
    )
    return f"""### GPU parallel-validation scaling (RTX PRO 6000 Blackwell, 300 W)

![GPU scaling]({_chart_path_for_readme(chart)})

| Parallel envs | env-steps/s | Scaling efficiency |
|---|---|---|
{chr(10).join(rows)}

Efficiency declines monotonically; {knee_note}.
"""


def build_results_section(results_root: Path | None = None, charts_dir: Path | None = None) -> str:
    """Build the full auto-generated results section markdown (and its charts)."""
    root = results_root or BENCHMARKS_DIR
    charts = charts_dir or CHARTS_DIR
    charts.mkdir(parents=True, exist_ok=True)
    parts = [
        _ablation_block(root, charts),
        _classifier_block(root, charts),
        _feasibility_block(root, charts),
        _orchestration_block(root, charts),
        _gpu_block(root, charts),
        "_This section and its charts are generated by `benchmarks/render_readme.py` from "
        "the JSONs in `benchmarks/*/results/` — regenerate after re-running any benchmark; "
        "do not edit by hand._\n",
    ]
    return "\n".join(parts)


# ------------------------------------------------------------------ injection


def inject_section(readme_path: Path, content: str, begin: str, end: str) -> bool:
    """Replace the marked block in the README. Returns True if the file changed."""
    text = readme_path.read_text()
    if begin not in text or end not in text:
        raise ValueError(
            f"README markers not found ({begin.split(' ')[1]}) — add the marker block first"
        )
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    new_text = f"{head}{begin}\n\n{content}\n{end}{tail}"
    changed = new_text != text
    if changed:
        readme_path.write_text(new_text)
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the README is out of date (CI mode)"
    )
    args = parser.parse_args()

    section = build_results_section()
    if args.check:
        current = README.read_text()
        expected_block = f"{RESULTS_BEGIN}\n\n{section}\n{RESULTS_END}"
        if expected_block not in current:
            print("README results section is STALE — run: python benchmarks/render_readme.py")
            return 1
        print("README results section is up to date")
        return 0

    changed = inject_section(README, section, RESULTS_BEGIN, RESULTS_END)
    print(f"README results section {'updated' if changed else 'already up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
